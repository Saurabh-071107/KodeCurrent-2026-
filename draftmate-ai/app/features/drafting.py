"""Document drafting feature module."""
import json
import logging
from typing import Any

import structlog
from pydantic import ValidationError

from app.core.model_router import get_router, LLMMessage
from app.core.prompts import get_drafting_prompt, build_drafting_user_prompt
from app.schemas import DraftRequest, DraftResponse, DocumentType, Jurisdiction, FactExtractionResponse

logger = structlog.get_logger(__name__)


class DraftingError(Exception):
    """Drafting specific errors."""

    pass


async def generate_draft(request: DraftRequest) -> DraftResponse:
    """
    Generate a legal document draft from extracted facts.

    Args:
        request: DraftRequest with document type, facts, and options

    Returns:
        DraftResponse with structured document sections and metadata

    Raises:
        DraftingError: If drafting fails
    """
    router = get_router()
    adapter = router.primary

    if not adapter:
        raise DraftingError("No LLM adapter configured. Please set LLM_API_KEY and LLM_MODEL.")

    # Build prompts
    jurisdiction_str = request.jurisdiction.value if request.jurisdiction else None
    system_prompt = get_drafting_prompt(request.document_type, jurisdiction_str)

    # Convert request to dict for prompt building
    request_dict = {
        "document_type": request.document_type.value,
        "facts": request.facts.model_dump() if request.facts else {},
        "jurisdiction": jurisdiction_str,
        "custom_instructions": request.custom_instructions,
    }
    user_prompt = build_drafting_user_prompt(request_dict)

    messages = [
        LLMMessage(role="system", content=system_prompt),
        LLMMessage(role="user", content=user_prompt),
    ]

    try:
        logger.info(
            "drafting_started",
            document_type=request.document_type.value,
            jurisdiction=jurisdiction_str,
            facts_sections=len(request.facts.user_provided_facts) + len(request.facts.inferred_facts) if request.facts else 0,
        )

        response = await adapter.chat(messages, temperature=0.3, max_tokens=6000)

        # Parse and validate JSON response
        parsed = _parse_drafting_response(response.content)

        # Validate against schema
        validated = DraftResponse.model_validate(parsed)

        # Ensure disclaimer is present
        if not validated.disclaimer or "legal advice" not in validated.disclaimer.lower():
            validated.disclaimer = (
                "This document is generated by an AI assistant and does not constitute legal advice. "
                "Please consult with a qualified attorney before using this document for any legal purpose."
            )

        logger.info(
            "drafting_completed",
            document_type=request.document_type.value,
            sections_count=len(validated.sections),
            placeholders_count=len(validated.placeholders),
            review_status=validated.review_status,
        )

        return validated

    except json.JSONDecodeError as e:
        logger.error("drafting_json_error", error=str(e), response_preview=response.content[:200])
        raise DraftingError(f"LLM returned invalid JSON: {str(e)}")
    except ValidationError as e:
        logger.error("drafting_validation_error", error=str(e), response_preview=response.content[:200])
        raise DraftingError(f"LLM response failed validation: {str(e)}")
    except Exception as e:
        logger.error("drafting_error", error_type=type(e).__name__, error=str(e))
        raise DraftingError(f"Draft generation failed: {str(e)}")


def _parse_drafting_response(content: str) -> dict[str, Any]:
    """Parse and clean LLM response for drafting."""
    content = content.strip()

    # Find JSON object
    start = content.find("{")
    end = content.rfind("}") + 1

    if start == -1 or end == 0:
        raise json.JSONDecodeError("No JSON object found in response", content, 0)

    json_str = content[start:end]
    return json.loads(json_str)